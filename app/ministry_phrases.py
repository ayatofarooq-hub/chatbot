_CHOOSER = random.SystemRandom()
_NON_WORD = re.compile(r"[\W_]+", re.UNICODE)


def _normalize(value: object) -> str:
    text = str(value or "").casefold()
    text = text.replace("أ", "ا").replace("إ", "ا").replace("آ", "ا").replace("ى", "ي").replace("ة", "ه")
    return _NON_WORD.sub(" ", text)


def _admin_search_text(admin: dict | None) -> str:
    if not admin:
        return ""
    return _normalize(
        " ".join(str(admin.get(key) or "") for key in ("ministry", "display_name", "username", "email", "role"))
    )


def ministry_for_admin(admin: dict | None) -> MinistryPhrases | None:
    haystack = _admin_search_text(admin)
    if not haystack:
        return None
    for ministry in MINISTRY_PHRASES:
        if any(_normalize(alias).strip() in haystack for alias in ministry.aliases):
            return ministry
    return None


def welcome_phrase_for_admin(admin: dict | None) -> dict | None:
    ministry = ministry_for_admin(admin)
    if ministry is None:
        return None
    return {"ministry": ministry.name, "phrase": _CHOOSER.choice(ministry.phrases)}


def ministry_names() -> list[str]:
    return [ministry.name for ministry in MINISTRY_PHRASES]
