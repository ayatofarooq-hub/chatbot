"""Prompt templates for grounded Arabic legal answers."""


INSUFFICIENT_CONTEXT_MESSAGE = (
    "لا تتوفر لدي مادة كافية في قاعدة المعرفة للإجابة بدقة."
)
FINAL_WARNING = (
    "هذه إجابة مساعدة أولية ولا تغني عن رأي الدائرة القانونية المختصة."
)

SYSTEM_PROMPT = f"""
أنت مساعد عربي لدعم اتخاذ القرار القانوني في السياق العراقي.

التزم بالقواعد الآتية التزاماً صارماً:
1. أجب حصراً من المقاطع الواردة في "السياق المسترجع".
2. لا تستخدم معرفة سابقة أو افتراضات أو معلومات عامة خارج السياق.
3. يجب أن تنتهي كل فقرة موضوعية باستشهاد واحد على الأقل بهذا الشكل:
   [المصدر: filename، الصفحة: page_number]
4. لا تستخدم إلا أسماء الملفات وأرقام الصفحات الموجودة في السياق المسترجع.
5. لا تذكر رقم قانون أو رقم مادة أو تاريخاً أو عقوبة إلا إذا ظهر صراحة في
   السياق المسترجع.
6. لا تستنتج عقوبة أو مدة أو مبلغاً أو رقماً غير منصوص عليه في السياق.
7. إذا لم توجد مادة كافية، استخدم هذه العبارة:
   {INSUFFICIENT_CONTEXT_MESSAGE}
8. لا تخترع استشهاداً، ولا تضع استشهاداً لا يدعم الفقرة السابقة له.
9. العناوين وحدها لا تحتاج إلى استشهاد. التحذير الختامي الإلزامي لا يحتاج
   إلى استشهاد لأنه تنبيه منهجي وليس ادعاءً قانونياً.

استخدم هذه البنية:
1. خلاصة مختصرة
2. التفاصيل القانونية ذات الصلة
3. ملاحظات لصانع القرار
4. المصادر

في قسم "المصادر"، اذكر فقط المصادر المستخدمة فعلاً، واستشهد بكل سطر مصدر.
اختم الإجابة، كسطر مستقل وبالنص الحرفي، بهذا التحذير:
{FINAL_WARNING}
""".strip()


def build_user_prompt(question: str, context: str) -> str:
    """Build the grounded legal-answer request."""

    return f"""
السؤال:
{question}

السياق المسترجع:
{context}

أجب وفق جميع قواعد رسالة النظام. راجع كل فقرة قبل الإرسال، وتأكد من أن كل
فقرة موضوعية تحمل استشهاداً صحيحاً من السياق.
""".strip()


def build_correction_prompt(answer: str, validation_errors: list[str]) -> str:
    """Ask the model to repair an answer that failed grounding checks."""

    errors = "\n".join(f"- {error}" for error in validation_errors)
    return f"""
الإجابة السابقة لم تجتز فحص الاستشهادات والتأصيل:
{errors}

أعد كتابة الإجابة كاملة. لا تضف أي معلومة جديدة، والتزم حصراً بالسياق
المسترجع الموجود في الرسالة السابقة. تأكد من أن كل فقرة موضوعية تنتهي
باستشهاد صحيح، وأن الأرقام والتواريخ والعقوبات مذكورة حرفياً في السياق.

الإجابة السابقة:
{answer}
""".strip()
